/**
 * Writes src/page/template-thumbnails.ts from whatever is in assets/templates.
 *
 * Metro resolves require() at build time, so the paths have to be literal — a
 * map built from a directory listing at runtime would bundle nothing. Run by
 * build-template-thumbnails.mjs; safe to run on its own.
 */
import { readdirSync, writeFileSync } from "node:fs";

const ids = readdirSync("assets/templates")
  .filter((f) => f.endsWith(".webp"))
  .map((f) => f.replace(/\.webp$/, ""))
  .sort();

const body = ids.map((id) => `  "${id}": require("../../assets/templates/${id}.webp"),`).join("\n");

writeFileSync(
  "src/page/template-thumbnails.ts",
  `/**
 * A photograph of every template, as the website draws it.
 *
 * Generated by scripts/build-template-thumbnails.mjs — do not edit by hand.
 * The app renders thirty families through five archetypes and cannot draw the
 * difference between them, so the picker shows these instead of a swatch.
 * Re-run the script when a template changes on the web; nothing here updates
 * on its own, because the website's deploy does not either.
 */
export const TEMPLATE_THUMBNAILS: Record<string, number | undefined> = {
${body}
};
`,
);

console.log(`wrote src/page/template-thumbnails.ts with ${ids.length} templates`);
